def _sections(doc: str) -> dict[str, str]:
    """Split a Google-style docstring into its named sections."""
    parts = _SECTION.split(doc)
    found: dict[str, str] = {}
    for heading, body in zip(parts[1::2], parts[2::2], strict=True):
        found[heading] = inspect.cleandoc(body).strip()
    return found


def _entries(section: str) -> list[str]:
    """Split a Google-style section into entries; indented lines continue one."""
    entries: list[str] = []
    for line in section.splitlines():
        if not line.strip():
            continue
        if entries and line[:1].isspace():
            entries[-1] = f"{entries[-1]} {line.strip()}"
        else:
            entries.append(line.strip())
    return entries


def _module_group(module: str) -> str:
    """The group a module names: its last segment, or the package above a ``register`` module.

    A module called ``register`` names the act, not the feature: pvl-core
    registers its jobs and transfer-link tools from ``_jobs.register`` and
    ``_transfer.register``, and a project cannot tag a library's tool (#760).
    """
    parts = [part.lstrip("_") for part in module.split(".")]
    if len(parts) > 1 and parts[-1] == "register":
        parts.pop()
    return parts[-1]


def _group_of(tool: Any) -> str:
    groups = sorted(
        t[len(GROUP_TAG) :] for t in tool.tags or () if t.startswith(GROUP_TAG)
    )
    if len(groups) > 1:
        raise GenerationError(
            f"tool {tool.name} carries two group tags: {', '.join(groups)}"
        )
    group = groups[0] if groups else _module_group(tool.fn.__module__)
    if group == "index":
        raise GenerationError(
            f"tool {tool.name}: group 'index' would overwrite the tools jump table; "
            "pick another group: tag"
        )
    return group


def _security(annotations: Any) -> list[str]:
    """The security line, read the way a client reads the annotations.

    The MCP spec's defaults apply where a hint is unset: not read-only, and
    destructive. An unstated hint is therefore rendered as what a client
    assumes, never as something milder.
    """
    if annotations is None:
        return [
            "No annotations: clients assume it changes state and may be destructive."
        ]
    lines = []
    if annotations.read_only_hint:
        lines.append("Read-only.")
    elif annotations.destructive_hint:
        lines.append("Destructive.")
    elif annotations.destructive_hint is False:
        lines.append("Changes state, not destructive.")
    else:
        lines.append("Changes state; may be destructive (no destructive hint given).")
    if annotations.idempotent_hint:
        lines.append("Idempotent.")
    if annotations.open_world_hint:
        lines.append("Reaches outside the server.")
    return lines


def _visibility(meta: Any) -> list[str]:
    """The MCP Apps visibility hint (``meta.ui.visibility``), when set."""
    ui = meta.get("ui") if isinstance(meta, dict) else None
    visible = ui.get("visibility") if isinstance(ui, dict) else None
    if not visible:
        return []
    return [f"Visible to: {', '.join(str(v) for v in visible)}."]


def _schema_type(prop: dict[str, Any]) -> str:
    if "enum" in prop:
        return " | ".join(str(v) for v in prop["enum"])
    if "anyOf" in prop:
        return " | ".join(_schema_type(p) for p in prop["anyOf"])
    if "$ref" in prop:
        return str(prop["$ref"]).rsplit("/", 1)[-1]
    kind = prop.get("type", "any")
    if kind == "array" and "items" in prop:
        return f"array of {_schema_type(prop['items'])}"
    return str(kind)


def _params(schema: dict[str, Any]) -> list[Param]:
    required = set(schema.get("required") or ())
    defs = schema.get("$defs") or {}
    out = []
    for name, prop in (schema.get("properties") or {}).items():
        resolved = defs.get(str(prop.get("$ref", "")).rsplit("/", 1)[-1], prop)
        if name in required:
            default = "required"
        elif "default" in prop:
            default = json.dumps(prop["default"])
        else:
            default = "optional"
        out.append(
            Param(
                name,
                _schema_type(resolved),
                default,
                str(prop.get("description") or ""),
            )
        )
    return out


def _output_type(schema: dict[str, Any] | None) -> str:
    if not schema:
        return ""
    if schema.get("x-fastmcp-wrap-result"):
        return _schema_type(schema["properties"]["result"])
    return _schema_type(schema)


def _tool_entry(tool: Any) -> ToolEntry:
    sections = _sections(inspect.getdoc(tool.fn) or "")
    raises = _entries(sections.get("Raises", ""))
    tags = sorted(t for t in tool.tags or () if not t.startswith(GROUP_TAG))
    return ToolEntry(
        name=tool.name,
        title=(tool.annotations.title if tool.annotations else None)
        or tool.title
        or tool.name,
        group=_group_of(tool),
        security=_security(tool.annotations) + _visibility(tool.meta),
        tags=tags,
        description=(tool.description or "").strip(),
        params=_params(tool.parameters or {}),
        returns=sections.get("Returns", ""),
        raises=raises,
        output_type=_output_type(tool.output_schema),
    )


def _cli_command(name: str, cmd: Any) -> CliCommand:
    """One click command as arguments and visible options."""
    arguments, options = [], []
    for param in cmd.params:
        help_text = getattr(param, "help", "") or ""
        if param.param_type_name == "argument":
            arguments.append(CliArgument(str(param.name).upper(), help_text))
        elif param.param_type_name == "option" and not getattr(param, "hidden", False):
            default = "" if param.default is None else str(param.default)
            envvar = param.envvar if isinstance(param.envvar, str) else ""
            options.append(CliOption(param.opts[0], envvar, default, help_text))
    return CliCommand(name, cmd.help or "", arguments, options)


def _cli(app: typer.Typer, name: str) -> Cli:
    import typer.main

    # typer vendors its own click, so duck-type the objects instead of
    # isinstance checks against the click package.
    root = typer.main.get_command(app)
    members = getattr(root, "commands", None)
    pairs = members.items() if members is not None else [(root.name, root)]
    commands = [
        _cli_command(str(cmd_name), cmd)
        for cmd_name, cmd in pairs
        if not getattr(cmd, "hidden", False)
    ]
    return Cli(name, root.help or "", commands)


def collect(server: FastMCP, app: typer.Typer, command_name: str) -> Reference:
    """Read every registered component of *server* and *app*."""

    async def _list() -> tuple[Any, Any, Any, Any]:
        return (
            await server.list_tools(),
            await server.list_resources(),
            await server.list_resource_templates(),
            await server.list_prompts(),
        )

    tools, resources, templates, prompts = asyncio.run(_list())
    ref = Reference()
    for tool in tools:
        entry = _tool_entry(tool)
        ref.groups.setdefault(entry.group, []).append(entry)
    for res in resources:
        ref.resources.append(
            ResourceEntry(
                res.name, str(res.uri), res.description or "", res.mime_type or "", []
            )
        )
    for tpl in templates:
        params = list((tpl.parameters or {}).get("properties") or {})
        ref.resources.append(
            ResourceEntry(
                tpl.name,
                tpl.uri_template,
                tpl.description or "",
                tpl.mime_type or "",
                params,
            )
        )
    for prompt in prompts:
        ref.prompts.append(
            PromptEntry(
                prompt.name,
                prompt.description or "",
                [
                    PromptArg(a.name, bool(a.required), a.description or "")
                    for a in prompt.arguments or ()
                ],
            )
        )
    ref.cli = _cli(app, command_name)
    return ref


