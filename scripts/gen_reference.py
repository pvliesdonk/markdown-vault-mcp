MARKER = (
    "<!-- generated by scripts/gen_reference.py; edit the docstrings, not this page -->"
)
GROUP_TAG = "group:"
NAV_START = "GENERATED-NAV-TOOLS-START"
NAV_END = "GENERATED-NAV-TOOLS-END"
SECURITY_MODEL = "../../security-model.md"

# The Google-style headings FastMCP strips from a docstring when it builds
# the wire description; the same set tests/test_model_facing_text.py pins.
_SECTION = re.compile(
    r"^[ \t]*(Args|Arguments|Parameters|Returns|Yields|Raises|Examples?):[ \t]*$",
    re.MULTILINE,
)
_COMMENT_ONLY = re.compile(r"<!--.*?-->", re.DOTALL)
_SLOT = re.compile(
    r"<!-- (DOMAIN-[A-Za-z0-9_.-]+?)-START -->\n(.*?)<!-- \1-END -->", re.DOTALL
)


class GenerationError(Exception):
    """The reference cannot be generated as the code stands."""


class BuildError(GenerationError):
    """The project's server or CLI could not be built (exit 2)."""


