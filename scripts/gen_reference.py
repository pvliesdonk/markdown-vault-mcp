#!/usr/bin/env python3
"""Generate the Reference pages from the registered server (#716).

Builds the project's server once and writes ``docs/reference/`` from what it
registers: one page per tool group, the tools jump table, resources,
prompts and the command line.  A fact on these pages changes at its source
(a docstring, an annotation, a CLI option); prose lives only in the
``DOMAIN-INTRO`` and ``DOMAIN-EXAMPLE-<name>`` slots, which survive
regeneration.

A tool's group is its ``group:<slug>`` tag, else the last segment of the
registering module (``pkg._tools.reader`` -> ``reader``), or the package
above it when that segment is ``register`` (``pkg._jobs.register`` ->
``jobs``).  The description a page shows is the wire description FastMCP
sends, so the two cannot disagree; ``Returns:`` and ``Raises:`` come from
the raw docstring, which the wire drops.

The script is template-owned and byte-identical in every project: it reads
``python_module`` and ``project_name`` from ``.copier-answers.yml`` and
imports ``<module>.server.make_server`` and ``<module>.cli.app``.  The server
is built for the ``http`` transport, the widest surface: a component a
project registers for HTTP alone, such as the transfer-link tools, is
documented too (#749).  Variables a project's ``from_env`` requires, and
what its HTTP-only wiring needs at build time (a transfer project's
``<PREFIX>_BASE_URL``), come from ``[tool.docs-reference] env`` in
``pyproject.toml``.

Usage::

    python scripts/gen_reference.py            # write docs/reference/ and the nav region
    python scripts/gen_reference.py --check    # exit 1 when a page or the nav is stale

Run from the project root; it reads and writes the current directory.
"""

