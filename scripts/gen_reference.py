def _first_sentence(text: str) -> str:
    guard = r"(?<!\be\.g\.)(?<!\bi\.e\.)(?<!\betc\.)(?<!\bvs\.)(?<!\bapprox\.)"
    return re.split(guard + r"(?<=[.!?])\s", text.strip(), maxsplit=1)[0]


def _title(slug: str) -> str:
    text = slug.replace("-", " ").replace("_", " ")
    return text[:1].upper() + text[1:]


def _slot(name: str, body: str, placeholder: str) -> str:
    content = body if body.strip() else placeholder + "\n"
    return f"<!-- {name}-START -->\n{content}<!-- {name}-END -->\n"


def _front(description: str) -> str:
    return f"---\ndescription: {json.dumps(description)}\nkind: reference\n---\n\n{MARKER}\n\n"


def _existing_slots(path: Path) -> dict[str, str]:
    if not path.exists():
        return {}
    return dict(_SLOT.findall(path.read_text(encoding="utf-8-sig")))


def _table(header: Iterable[str], rows: Iterable[Iterable[str]]) -> str:
    head = list(header)
    lines = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    lines.extend("| " + " | ".join(_cell(c) for c in row) + " |" for row in rows)
    return "\n".join(lines) + "\n"


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


# Stretches _prose never touches: code spans and Markdown links.  A code span
# is CommonMark's: a run of backticks closed by the next run of the same
# length, so an RST-style ``double`` span is one span, not two empty ones (#747).
_OPENER = re.compile(r"[`\[]")
_RUN = re.compile(r"`+")
# Link text holds no bracket and the target no parenthesis, so a failed match
# stops at the next opener and the scan stays linear.
_LINK = re.compile(r"\[[^\[\]]*\]\([^()]*\)")
# Not next to a backtick: an unclosed run is literal text, and wrapping the
# word beside it would lengthen the run into a different one.
_IDENTIFIER = re.compile(r"(?<!`)\b[A-Za-z0-9]+(?:_[A-Za-z0-9]+)+\b(?!`)")


def _literals(text: str) -> Iterator[tuple[int, int]]:
    """Yield ``(start, end)`` of each code span and link, left to right.

    Whichever starts first wins, as in CommonMark.  A backtick run with no
    closing run of its length is literal text.  Linear in ``len(text)``:
    every run's closer is looked up, not searched for.
    """
    runs = [(m.start(), m.end()) for m in _RUN.finditer(text)]
    closer: dict[int, int] = {}  # run start -> end of the next run as long
    later: dict[int, int] = {}  # run length -> end of the nearest later run
    for start, end in reversed(runs):
        if end - start in later:
            closer[start] = later[end - start]
        later[end - start] = end
    run_end = dict(runs)
    position = 0
    while opener := _OPENER.search(text, position):
        start = opener.start()
        if text[start] == "[":
            link = _LINK.match(text, start)
            position = link.end() if link else start + 1
            if link:
                yield start, link.end()
        elif start in closer:
            position = closer[start]
            yield start, position
        else:
            position = run_end.get(start, start + 1)


def _prose(text: str) -> str:
    """Format snake_case identifiers in docstring prose as code.

    The words stay the wire's words; only the formatting changes, so Vale
    spell-checks prose and leaves identifiers alone. Existing code spans and
    links are left as they are.
    """
    out = []
    position = 0
    for start, end in _literals(text):
        out.append(_code_identifiers(text[position:start]))
        out.append(text[start:end])
        position = end
    out.append(_code_identifiers(text[position:]))
    return "".join(out)


def _code_identifiers(prose: str) -> str:
    return _IDENTIFIER.sub(lambda m: f"`{m.group(0)}`", prose)


def _default_cell(default: str) -> str:
    return default if default in ("required", "optional") else f"`{default}`"


def _tool_section(tool: ToolEntry, slots: dict[str, str], used: set[str]) -> str:
    out = [f"## `{tool.name}`\n\n"]
    if tool.title != tool.name:
        out.append(f"**{tool.title}.** ")
    out.append(" ".join(tool.security))
    if tool.tags:
        out.append(f" Tags: {', '.join(f'`{t}`' for t in tool.tags)}.")
    out.append("\n\n")
    if tool.description:
        out.append(_prose(tool.description) + "\n\n")
    out.append("**Parameters**\n\n")
    if tool.params:
        out.append(
            _table(
                ("Name", "Type", "Default", "Description"),
                (
                    (
                        f"`{p.name}`",
                        f"`{p.type}`",
                        _default_cell(p.default),
                        _prose(p.description),
                    )
                    for p in tool.params
                ),
            )
        )
    else:
        out.append("None.\n")
    out.append("\n**Returns**\n\n")
    out.append(
        (
            _prose(tool.returns)
            or (f"`{tool.output_type}`" if tool.output_type else "Nothing.")
        )
        + "\n\n"
    )
    if tool.raises:
        out.append("**Outcomes and errors**\n\n")
        out.extend(f"- {_prose(line)}\n" for line in tool.raises)
        out.append("\n")
    slot = f"DOMAIN-EXAMPLE-{tool.name}"
    used.add(slot)
    out.append(
        _slot(
            slot,
            slots.get(slot, ""),
            "<!-- A worked example for this tool; kept across regeneration. -->",
        )
    )
    out.append("\n")
    return "".join(out)


def _page(
    path: Path, description: str, heading: str, body_fn: Any, preface: str = ""
) -> str:
    """Assemble a page: front matter, heading, the intro slot, *preface*, body.

    *preface* is template-owned prose that every regeneration rewrites (unlike
    the slots), used for the client guidance on the prompts and resources pages.
    The shipped seed pages under ``docs/reference/`` carry the same text, so a
    fresh render passes ``--check``; change the constant and the seed together.
    """
    slots = _existing_slots(path)
    used = {"DOMAIN-INTRO"}
    body = body_fn(slots, used)
    orphans = sorted(set(slots) - used)
    if orphans:
        raise GenerationError(
            f"{path}: slot {', '.join(orphans)} matches no registered component; "
            "move its content or delete the slot"
        )
    intro = _slot(
        "DOMAIN-INTRO",
        slots.get("DOMAIN-INTRO", ""),
        "<!-- A short orientation for this page; task guidance belongs under Use. Kept across regeneration. -->",
    )
    return _front(description) + f"# {heading}\n\n" + intro + "\n" + preface + body


def _group_page(group: str, tools: list[ToolEntry], path: Path) -> str:
    def body(slots: dict[str, str], used: set[str]) -> str:
        return "".join(_tool_section(t, slots, used) for t in tools).rstrip("\n") + "\n"

    return _page(
        path, f"Reference for the {_title(group)} group of tools.", _title(group), body
    )


def _index_page(ref: Reference, path: Path) -> str:
    def body(_slots: dict[str, str], _used: set[str]) -> str:
        rows = [
            (
                _title(group),
                f"[`{t.name}`]({group}.md#{t.name})",
                _prose(t.title),
                _prose(_first_sentence(t.description)),
            )
            for group, tools in ref.groups.items()
            for t in tools
        ]
        text = (
            "Every tool runs with the server's own privileges; the "
            f"[security model]({SECURITY_MODEL}) says what that reaches.\n\n"
        )
        return text + _table(("Group", "Tool", "Title", "Does"), rows)

    return _page(path, "Every tool this server registers, by group.", "Tools", body)


_PROMPTS_PREFACE = """## Running a prompt

A prompt is a template this server fills from the arguments listed with it and hands to your client as a message, so a task starts with the server's own instructions. It runs the same tools with the same access as anything you type. How to start one depends on the client:

- **Claude Code** lists each prompt in the `/` menu as `/<server>:<prompt> (MCP)`, where `<server>` is the name you gave this server when you added it. Typing `/mcp__<server>__<prompt>` runs it too; arguments follow it separated by spaces, each a single token.
- **claude.ai and Claude Desktop** offer a connector's prompts from the compose area's **+** menu once the connector is added.

"""

_RESOURCES_PREFACE = """## Reading a resource

A resource is data this server serves at a URI, for a client to attach to the conversation rather than for the model to call. In Claude Code, mention one as `@<server>:<uri>`, where `<server>` is the name you gave this server when you added it; a resource template takes its parameters in the URI.

"""


def _resources_page(ref: Reference, path: Path) -> str:
    def body(_slots: dict[str, str], _used: set[str]) -> str:
        if not ref.resources:
            return "This server registers no resources.\n"
        out = []
        for r in ref.resources:
            out.append(f"## `{r.name}`\n\n`{r.uri}`")
            if r.mime_type:
                out.append(f" ({r.mime_type})")
            out.append("\n\n")
            if r.description:
                out.append(_prose(r.description) + "\n\n")
            if r.parameters:
                out.append(
                    "Parameters: " + ", ".join(f"`{p}`" for p in r.parameters) + ".\n\n"
                )
        return "".join(out).rstrip("\n") + "\n"

    return _page(
        path,
        "The resources and resource templates this server serves.",
        "Resources",
        body,
        preface=_RESOURCES_PREFACE,
    )


def _prompts_page(ref: Reference, path: Path) -> str:
    def body(slots: dict[str, str], used: set[str]) -> str:
        if not ref.prompts:
            return "This server registers no prompts.\n"
        out = []
        for p in ref.prompts:
            out.append(f"## `{p.name}`\n\n")
            if p.description:
                out.append(_prose(p.description) + "\n\n")
            if p.arguments:
                out.append(
                    _table(
                        ("Argument", "Required", "Description"),
                        (
                            (
                                f"`{a.name}`",
                                "yes" if a.required else "no",
                                _prose(a.description),
                            )
                            for a in p.arguments
                        ),
                    )
                    + "\n"
                )
            slot = f"DOMAIN-EXAMPLE-{p.name}"
            used.add(slot)
            out.append(
                _slot(
                    slot,
                    slots.get(slot, ""),
                    "<!-- A worked example for this prompt; kept across regeneration. -->",
                )
            )
            out.append("\n")
        return "".join(out).rstrip("\n") + "\n"

    return _page(
        path,
        "The prompt templates this server offers to MCP clients.",
        "Prompts",
        body,
        preface=_PROMPTS_PREFACE,
    )


def _command_section(cli_name: str, c: CliCommand) -> str:
    out = [f"## `{cli_name} {c.name}`\n\n"]
    if c.help:
        out.append(_prose(c.help) + "\n\n")
    if c.arguments:
        argument_rows = ((f"`{a.name}`", _prose(a.help)) for a in c.arguments)
        out.append(_table(("Argument", "Description"), argument_rows) + "\n")
    if c.options:
        rows = (
            (
                f"`{o.name}`",
                f"`{o.envvar}`" if o.envvar else "",
                o.default,
                _prose(o.help),
            )
            for o in c.options
        )
        out.append(_table(("Option", "Env var", "Default", "Description"), rows) + "\n")
    return "".join(out)


def _cli_page(ref: Reference, path: Path) -> str:
    def body(_slots: dict[str, str], _used: set[str]) -> str:
        intro = _prose(ref.cli.help) + "\n\n" if ref.cli.help else ""
        sections = "".join(_command_section(ref.cli.name, c) for c in ref.cli.commands)
        return (intro + sections).rstrip("\n") + "\n"

    return _page(
        path,
        f"The `{ref.cli.name}` command line: commands, options and their environment variables.",
        "Command line",
        body,
    )


def render(ref: Reference, docs: Path) -> dict[str, str]:
    """Return every generated page, path relative to *docs* -> text."""
    pages: dict[str, str] = {}
    for group, tools in ref.groups.items():
        rel = f"reference/tools/{group}.md"
        pages[rel] = _group_page(group, tools, docs / rel)
    for rel, fn in (
        ("reference/tools/index.md", _index_page),
        ("reference/resources.md", _resources_page),
        ("reference/prompts.md", _prompts_page),
        ("reference/cli.md", _cli_page),
    ):
        pages[rel] = fn(ref, docs / rel)
    # After every page is in: the jump table sits beside the group pages and
    # would otherwise count as a vanished group (#761).
    _guard_stale(docs, pages)
    return pages


def _stale(docs: Path, pages: dict[str, str]) -> list[Path]:
    """Generated group pages on disk that this run did not produce."""
    tools = docs / "reference" / "tools"
    if not tools.is_dir():
        return []
    return sorted(
        p
        for p in tools.glob("*.md")
        if f"reference/tools/{p.name}" not in pages
        and MARKER in p.read_text(encoding="utf-8-sig")
    )


def _guard_stale(docs: Path, pages: dict[str, str]) -> None:
    """Refuse to continue while a vanished group's page still holds prose."""
    for stale in _stale(docs, pages):
        written = [
            name
            for name, body in _existing_slots(stale).items()
            if _COMMENT_ONLY.sub("", body).strip()
        ]
        if written:
            raise GenerationError(
                f"{stale}: no tool group writes this page any more, but its slot(s) "
                f"{', '.join(written)} hold content; move it to the new group page, "
                "then delete the file"
            )


def check(docs: Path, pages: dict[str, str]) -> list[str]:
    """Return diff lines for every page that differs from disk, and stale files."""
    lines: list[str] = []
    for rel, text in sorted(pages.items()):
        path = docs / rel
        current = path.read_text(encoding="utf-8-sig") if path.exists() else ""
        if current != text:
            lines.extend(
                difflib.unified_diff(
                    current.splitlines(),
                    text.splitlines(),
                    f"docs/{rel}",
                    "generated",
                    lineterm="",
                )
            )
    lines.extend(f"stale: {p} (no longer generated)" for p in _stale(docs, pages))
    return lines


def write(docs: Path, pages: dict[str, str]) -> None:
    """Write every page and delete stale generated ones."""
    for stale in _stale(docs, pages):
        stale.unlink()
    for rel, text in pages.items():
        path = docs / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")


def update_nav(mkdocs_text: str, ref: Reference) -> str:
    """Rewrite the GENERATED-NAV-TOOLS region with one entry per group."""
    lines = mkdocs_text.splitlines(keepends=True)
    starts = [i for i, line in enumerate(lines) if NAV_START in line]
    ends = [i for i, line in enumerate(lines) if NAV_END in line]
    if len(starts) != 1 or len(ends) != 1 or ends[0] < starts[0]:
        raise GenerationError(f"mkdocs.yml: expected one {NAV_START}/{NAV_END} region")
    indent = lines[starts[0]][: len(lines[starts[0]]) - len(lines[starts[0]].lstrip())]
    entries = [f"{indent}- {_title(g)}: reference/tools/{g}.md\n" for g in ref.groups]
    return "".join(lines[: starts[0] + 1] + entries + lines[ends[0] :])


