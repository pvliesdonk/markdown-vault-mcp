def _project(root: Path) -> tuple[str, str]:
    """Return ``(python_module, project_name)`` for the project at *root*.

    ``.copier-answers.yml`` is the source while the project tracks the
    template; a detached project has deleted it, so ``[project.scripts]`` in
    ``pyproject.toml`` (``name = "module.cli:main"``) is the fallback.
    """
    answers = root / ".copier-answers.yml"
    if answers.exists():
        data = yaml.safe_load(answers.read_text(encoding="utf-8")) or {}
        if data.get("python_module") and data.get("project_name"):
            return str(data["python_module"]), str(data["project_name"])
    try:
        pyproject = tomllib.loads((root / "pyproject.toml").read_text(encoding="utf-8"))
    except (OSError, tomllib.TOMLDecodeError) as exc:
        raise BuildError(f"cannot read {root / 'pyproject.toml'}: {exc}") from exc
    scripts = pyproject.get("project", {}).get("scripts", {})
    for name, target in scripts.items():
        module = str(target).split(":", 1)[0].rsplit(".", 1)[0]
        if module:
            return module, str(name)
    raise BuildError(
        f"{root}: neither .copier-answers.yml nor [project.scripts] names the package"
    )


def _preset_env(root: Path) -> None:
    try:
        data = tomllib.loads((root / "pyproject.toml").read_text(encoding="utf-8"))
    except (OSError, tomllib.TOMLDecodeError):
        return
    env = data.get("tool", {}).get("docs-reference", {}).get("env", {})
    for key, value in env.items():
        os.environ.setdefault(str(key), str(value))


def _build(root: Path) -> Reference:
    import importlib

    module, project_name = _project(root)
    _preset_env(root)
    sys.path.insert(0, str(root / "src"))
    try:
        server_mod = importlib.import_module(f"{module}.server")
        cli_mod = importlib.import_module(f"{module}.cli")
    except ImportError as exc:
        raise BuildError(f"cannot import {module}: {exc}") from exc
    # The server's own startup and request logs are noise here; errors still show.
    logging.disable(logging.WARNING)
    try:
        server = server_mod.make_server(transport="http")
    except Exception as exc:
        raise BuildError(
            f'make_server(transport="http") failed: {exc}. A required variable '
            "goes under [tool.docs-reference] env in pyproject.toml."
        ) from exc
    try:
        return collect(server, cli_mod.app, project_name)
    except AttributeError as exc:  # a tool without .fn (proxied or transformed)
        raise BuildError(f"cannot read a registered component: {exc}") from exc


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Generate docs/reference/ from the server; run at the project root."
    )
    parser.add_argument(
        "--check", action="store_true", help="report drift; write nothing"
    )
    args = parser.parse_args(argv)
    root = Path.cwd()
    docs = root / "docs"
    mkdocs = root / "mkdocs.yml"
    try:
        ref = _build(root)
        pages = render(ref, docs)
        nav = update_nav(mkdocs.read_text(encoding="utf-8"), ref)
    except OSError as exc:
        print(f"gen_reference: {exc}", file=sys.stderr)
        return 2
    except BuildError as exc:
        print(f"gen_reference: {exc}", file=sys.stderr)
        return 2
    except GenerationError as exc:
        print(f"gen_reference: {exc}", file=sys.stderr)
        return 1
    drift = check(docs, pages)
    if nav != mkdocs.read_text(encoding="utf-8"):
        drift.append("mkdocs.yml: the GENERATED-NAV-TOOLS region is stale")
    if args.check:
        for line in drift:
            print(line)
        print(f"gen_reference: {'stale' if drift else 'up to date'}")
        return 1 if drift else 0
    write(docs, pages)
    mkdocs.write_text(nav, encoding="utf-8", newline="\n")
    print(f"gen_reference: wrote {len(pages)} page(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
